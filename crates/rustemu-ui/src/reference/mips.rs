//! The MIPS32 reference, as MARS assembles and runs programs: the instructions (machine and
//! pseudo-instructions, one article for a family like `lb`/`lbu`), the directives, the system
//! calls of `syscall` and the registers. The forms of an instruction and what a pseudo-instruction
//! becomes are not written here: the window takes them from the assembler's own table.

/// An instruction article: one mnemonic or a family of close ones.
pub struct MipsInstr {
    /// Main mnemonic (lower case, as MIPS sources write it).
    pub name: &'static str,
    /// The other mnemonics of the article.
    pub aliases: &'static [&'static str],
    /// Group of the instruction list.
    pub group: MipsGroup,
    /// One line for lists and tooltips.
    pub summary: &'static str,
    /// The article.
    pub description: &'static str,
    /// Example code (assembles on its own).
    pub example: &'static str,
}

/// Groups of the MIPS instruction list.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum MipsGroup {
    /// add, sub, mult, div, ...
    Arithmetic,
    /// and, or, xor, nor, not
    Logic,
    /// Shifts and rotations.
    Shift,
    /// slt, seq, sge, ... (set a register to 0 or 1)
    Compare,
    /// lui, li, la, move, mfhi, movn, ...
    Move,
    /// Loads and stores.
    Memory,
    /// Conditional branches.
    Branch,
    /// j, jal, jr, jalr
    Jump,
    /// syscall, break, traps, coprocessor 0, nop
    System,
    /// Coprocessor 1: floating-point arithmetic, conversions, comparisons, loads and stores.
    Float,
}

impl MipsGroup {
    /// The groups in the order of the list.
    pub const ALL: [MipsGroup; 10] = [
        MipsGroup::Arithmetic,
        MipsGroup::Logic,
        MipsGroup::Shift,
        MipsGroup::Compare,
        MipsGroup::Move,
        MipsGroup::Memory,
        MipsGroup::Branch,
        MipsGroup::Jump,
        MipsGroup::System,
        MipsGroup::Float,
    ];
}

/// A directive of the MARS assembler.
pub struct MipsDirective {
    /// Name with its dot (`.word`).
    pub name: &'static str,
    /// One line for lists and tooltips.
    pub summary: &'static str,
    /// The article.
    pub description: &'static str,
    /// Example code.
    pub example: &'static str,
}

/// A service of `syscall` (its number goes in `$v0`).
pub struct Syscall {
    /// Service number.
    pub code: u32,
    /// Name (as MARS's table has it).
    pub name: &'static str,
    /// Arguments.
    pub input: &'static str,
    /// Results.
    pub output: &'static str,
    /// What else to know.
    pub note: &'static str,
    /// RustEmu8086 performs it (dialog windows are not supported yet).
    pub supported: bool,
    /// Example code (empty for the unsupported ones).
    pub example: &'static str,
}

