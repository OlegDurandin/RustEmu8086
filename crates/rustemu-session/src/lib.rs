//! Glue between the assembler and the emulator: loading programs, source-level debugging info.
//!
//! The session works with the emulated computer through [`Target`]: mapping addresses to source
//! lines, macro expansions, symbols, Step Over / Step Out and debugger expressions are the same
//! for every processor. What depends on the processor is chosen by [`Target::arch`]; the 8086
//! part (program formats, floppies, `segment:offset` symbols) is in [`x86`], the MIPS part
//! (MARS programs, flat addresses) in [`mips`].

#![warn(missing_docs)]

pub mod code;
mod detect;
pub mod expr;
pub mod mips;
pub mod step;
pub mod x86;

use std::collections::HashMap;

pub use detect::detect_arch;
use rustemu_asm::{LineInfo, Program, SymbolKind};
use rustemu_core::Machine;
use rustemu_core::machine::PROGRAM_SEG;
pub use rustemu_target::{Arch, Event, Flow, Frame, FrameKind, Target};

/// A loaded program together with its debug information.
pub struct Session {
    step_cache: std::cell::RefCell<Option<step::CachedStep>>,
    /// The emulated computer (the 8086 [`Machine`]; see [`Session::x86`]).
    pub target: Box<dyn Target>,
    /// The assembled program with its debug information (`None` for a binary loaded as is).
    pub program: Option<Program>,
    /// Raw executable bytes that were loaded (for Reload).
    loaded: Option<(Loadable, Vec<u8>)>,
    /// DOS command line parameters given to the program (PSP:80h) on every load.
    pub command_line: String,
    /// Physical address -> procedure, label or variable name of the loaded program.
    symbols_by_addr: HashMap<u32, String>,
    /// The MIPS program loaded (its own listing and data lines), None for the 8086.
    pub mips_program: Option<rustemu_mips::asm::Program>,
    /// Indices into `program.lines` sorted by image offset (for binary search).
    lines_sorted: Vec<usize>,
    /// First instruction of every macro expansion: (statement file, line, chain prefix) -> address.
    expansion_starts: HashMap<ExpansionKey, u32>,
}

/// A macro expansion: statement (file, line) + chain of enclosing macro body lines.
type ExpansionKey = (usize, u32, Vec<(usize, u32)>);

/// The source line shown to the user for an instruction (see [`Session::view_at`]).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct View {
    /// File index (into the program's files).
    pub file: usize,
    /// 1-based line number.
    pub line: u32,
    /// 0 = a statement of the program; n = line of the n-th nested macro definition.
    pub level: usize,
    /// The program statement the instruction belongs to (macro invocation for macro code).
    pub statement: (usize, u32),
}

/// Where an instruction comes from in the sources.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Location {
    /// File index and line of the statement (for macro code: the macro invocation).
    pub file: usize,
    /// 1-based line number of the statement.
    pub line: u32,
    /// For code generated by a macro: file index and line inside the macro definition.
    pub origin: Option<(usize, u32)>,
}

/// How executable bytes are loaded (by the file's extension or the program's format).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Loadable {
    /// A COM program at PSP:0100h.
    Com,
    /// An EXE (MZ) program.
    Exe,
    /// Raw bytes at `seg:off`.
    Bin {
        /// Load segment.
        seg: u16,
        /// Load offset.
        off: u16,
    },
    /// A boot sector at 0000:7C00h.
    Boot,
}

impl Default for Session {
    fn default() -> Self {
        Self::new()
    }
}

impl Session {
    /// A powered-on machine with nothing loaded.
    pub fn new() -> Self {
        Session {
            step_cache: Default::default(),
            target: Box::new(Machine::new()),
            program: None,
            loaded: None,
            command_line: String::new(),
            symbols_by_addr: HashMap::new(),
            lines_sorted: Vec::new(),
            mips_program: None,
            expansion_starts: HashMap::new(),
        }
    }

    /// Loads an assembled program (with source mapping).
    pub fn load_program(&mut self, prog: Program) -> Result<(), String> {
        let (kind, bytes) = match self.target.arch() {
            Arch::I8086 => {
                let bytes =
                    if prog.format == rustemu_asm::Format::Boot { prog.image.clone() } else { prog.file_bytes() };
                (Self::x86_loadable(&prog), bytes)
            }
            Arch::Mips32 => return Err("an 8086 program cannot run on the MIPS machine".into()),
        };
        self.load_bytes_with_program(kind, bytes, Some(prog))
    }

    /// Loads raw executable bytes without debug information.
    pub fn load_bytes(&mut self, kind: Loadable, bytes: Vec<u8>) -> Result<(), String> {
        self.load_bytes_with_program(kind, bytes, None)
    }

    /// Loads bytes and commits their matching debug information only after the
    /// machine has accepted the executable.
    fn load_bytes_with_program(
        &mut self,
        kind: Loadable,
        bytes: Vec<u8>,
        program: Option<Program>,
    ) -> Result<(), String> {
        match self.target.arch() {
            Arch::I8086 => self.x86_load(kind, &bytes, program.as_ref())?,
            Arch::Mips32 => return Err("8086 executables cannot run on the MIPS machine".into()),
        }
        self.step_cache.borrow_mut().take();
        self.program = program;
        self.loaded = Some((kind, bytes));
        self.index_symbols();
        self.index_lines();
        Ok(())
    }

    /// The executable loaded last, as it was loaded (e.g. to write it to a floppy).
    pub fn loaded_bytes(&self) -> Option<&[u8]> {
        self.loaded.as_ref().map(|(_, b)| &b[..])
    }

    /// Reloads the last program (fresh machine state, same breakpoints).
    pub fn reload(&mut self) -> Result<(), String> {
        if self.target.arch() == Arch::Mips32 {
            let bps = self.target.breakpoints().clone();
            self.mips_reload()?;
            *self.target.breakpoints_mut() = bps;
            return Ok(());
        }
        let bps = self.target.breakpoints().clone();
        let (kind, bytes) = self.loaded.clone().ok_or("nothing loaded")?;
        let program = self.program.clone();
        self.load_bytes_with_program(kind, bytes, program)?;
        *self.target.breakpoints_mut() = bps;
        Ok(())
    }

    /// Saves the machine together with the program and its debug information.
    pub fn save_state(&self) -> SessionState {
        SessionState {
            machine: self.target.save_state(),
            program: self.program.clone(),
            mips_program: self.mips_program.clone(),
            loaded: self.loaded.clone(),
        }
    }

    /// Returns to a state saved with [`Session::save_state`] (breakpoints are kept).
    pub fn restore_state(&mut self, s: SessionState) {
        self.target.restore_state(&s.machine);
        self.step_cache.borrow_mut().take();
        self.program = s.program;
        self.mips_program = s.mips_program;
        self.loaded = s.loaded;
        self.index_symbols();
        self.index_lines();
    }

    /// "Reset emulator and RAM": a powered-on machine with nothing loaded.
    pub fn unload(&mut self) {
        self.target.reset();
        self.step_cache.borrow_mut().take();
        self.program = None;
        self.mips_program = None;
        self.loaded = None;
        self.index_symbols();
        self.index_lines();
    }

    /// Physical address of the first byte of the load image.
    pub fn image_base(&self) -> Option<u32> {
        self.target.image_base()
    }

    fn index_lines(&mut self) {
        self.lines_sorted.clear();
        self.expansion_starts.clear();
        let (Some(p), Some(base)) = (&self.program, self.image_base()) else { return };
        self.lines_sorted = (0..p.lines.len()).collect();
        self.lines_sorted.sort_by_key(|&i| p.lines[i].image_offset);
        for l in p.lines.iter().filter(|l| l.is_code) {
            let addr = base + l.image_offset;
            for k in 1..=l.chain.len() {
                let key = (l.file, l.line, l.chain[..k - 1].to_vec());
                let e = self.expansion_starts.entry(key).or_insert(addr);
                *e = (*e).min(addr);
            }
        }
    }

    /// Debug info of the instruction at `addr`.
    pub fn line_info_at(&self, addr: u32) -> Option<&LineInfo> {
        let p = self.program.as_ref()?;
        let off = addr.checked_sub(self.image_base()?)?;
        let i = self.lines_sorted.partition_point(|&i| p.lines[i].image_offset <= off);
        let l = &p.lines[*self.lines_sorted.get(i.checked_sub(1)?)?];
        (off < l.image_offset + l.len).then_some(l)
    }

    /// The source line to show for the instruction at `addr`.
    ///
    /// Macro code is shown inside the macro definition (`into_macros`), except for the first
    /// instruction of an expansion: there execution is "at" the invocation line, so stepping
    /// over it runs the whole macro and a single step enters it.
    pub fn view_at(&self, addr: u32, into_macros: bool) -> Option<View> {
        let l = self.line_info_at(addr)?;
        let mut level = if into_macros { l.chain.len() } else { 0 };
        while level > 0 {
            let key = (l.file, l.line, l.chain[..level - 1].to_vec());
            if self.expansion_starts.get(&key) == Some(&addr) {
                level -= 1;
            } else {
                break;
            }
        }
        let (file, line) = if level == 0 { (l.file, l.line) } else { l.chain[level - 1] };
        Some(View { file, line, level, statement: (l.file, l.line) })
    }

    /// View of the current instruction (see [`Session::effective_pc`]).
    pub fn current_view(&self, into_macros: bool) -> Option<View> {
        self.view_at(self.effective_pc(), into_macros)
    }

    fn index_symbols(&mut self) {
        self.symbols_by_addr.clear();
        let Some(p) = &self.program else { return };
        // Several names at one address: procedures win over labels, labels over variables,
        // global names over macro locals.
        let mut ranks: HashMap<u32, u8> = HashMap::new();
        let mut names = HashMap::new();
        for s in &p.symbols {
            let rank = match s.kind {
                SymbolKind::Proc => 3,
                SymbolKind::Label => 2,
                SymbolKind::Variable => 1,
                _ => continue,
            } * 2
                + !s.is_macro_local() as u8;
            let Some(addr) = self.symbol_addr(s) else { return };
            if ranks.get(&addr).is_none_or(|&r| rank > r) {
                ranks.insert(addr, rank);
                names.insert(addr, s.name.clone());
            }
        }
        self.symbols_by_addr = names;
    }

    /// Physical address of a program symbol (procedures, labels, variables).
    pub fn symbol_addr(&self, s: &rustemu_asm::Symbol) -> Option<u32> {
        match self.target.arch() {
            Arch::I8086 => self.x86_symbol_addr(s),
            Arch::Mips32 => Some(s.value as u32),
        }
    }

    /// Procedure, label or variable name at a physical address (macro-local labels without their suffix).
    pub fn symbol_at(&self, addr: u32) -> Option<&str> {
        self.symbols_by_addr.get(&addr).map(|n| n.split("??").next().unwrap_or(n))
    }

    /// Full source location of the instruction at `addr`.
    pub fn location_at_addr(&self, addr: u32) -> Option<Location> {
        self.line_info_at(addr).map(|l| Location { file: l.file, line: l.line, origin: l.origin })
    }

    /// Full source location of the current instruction (see [`Session::effective_pc`]).
    pub fn current_location(&self) -> Option<Location> {
        self.location_at_addr(self.effective_pc())
    }

    /// Source location (file index, line) of the instruction at physical address `addr`.
    pub fn line_at_addr(&self, addr: u32) -> Option<(usize, u32)> {
        self.line_info_at(addr).map(|l| (l.file, l.line))
    }

    /// Source location of the current instruction. Inside the emulator's system code (8086: a
    /// BIOS/DOS service, e.g. while waiting for a key) this is the line of the calling instruction.
    pub fn current_line(&self) -> Option<(usize, u32)> {
        self.line_at_addr(self.effective_pc())
    }

    /// Physical address of the current instruction, or of the program instruction that called the
    /// emulator's system code running now ([`Target::system_caller`]; 8086: the `INT n` of a
    /// BIOS/DOS service).
    pub fn effective_pc(&self) -> u32 {
        self.target.system_caller().unwrap_or_else(|| self.target.pc())
    }

    /// Physical address of the first instruction generated for a source line.
    pub fn addr_of_line(&self, file: usize, line: u32) -> Option<u32> {
        self.addrs_of_line(file, line).first().copied()
    }

    /// Addresses where execution can stop for a source line: the first instruction of a statement
    /// (or of a macro invocation), and every expansion of a line inside a macro definition.
    pub fn addrs_of_line(&self, file: usize, line: u32) -> Vec<u32> {
        let (Some(p), Some(base)) = (&self.program, self.image_base()) else { return Vec::new() };
        let mut out = Vec::new();
        let mut first_direct = None;
        for l in p.lines.iter().filter(|l| l.is_code) {
            if l.origin == Some((file, line)) {
                out.push(base + l.image_offset);
            } else if l.file == file && l.line == line && first_direct.is_none() {
                first_direct = Some(base + l.image_offset);
            }
        }
        if let Some(a) = first_direct {
            out.insert(0, a);
        }
        out
    }

    /// Resolves a name of the loaded program for debugger expressions (case-insensitive).
    pub fn lookup_symbol(&self, name: &str) -> Option<expr::SymbolRef> {
        let p = self.program.as_ref()?;
        let s = p.symbols.iter().find(|s| s.name.eq_ignore_ascii_case(name))?;
        // MIPS: a name is its address (flat memory); [name] reads there.
        if self.target.arch() == Arch::Mips32 {
            return Some(expr::SymbolRef::Value(s.value));
        }
        Some(match s.kind {
            SymbolKind::Variable => {
                let (seg, off) = match self.target.arch() {
                    Arch::I8086 => self.x86_symbol_seg_off(s)?,
                    Arch::Mips32 => return None,
                };
                let size = s.size.unwrap_or(1).clamp(1, 8);
                // NASM: the name is the address, [name] the value.
                if p.dialect == rustemu_asm::Dialect::Nasm {
                    expr::SymbolRef::Address { seg, off, size }
                } else {
                    expr::SymbolRef::Variable { seg, off, size }
                }
            }
            SymbolKind::Segment => {
                let base = match self.target.arch() {
                    Arch::I8086 => self.x86_load_segment(),
                    Arch::Mips32 => 0,
                };
                expr::SymbolRef::Value(base as i64 + s.value)
            }
            _ => expr::SymbolRef::Value(s.value),
        })
    }

    /// Compiles a debugger expression against the loaded program's symbols.
    pub fn compile(&self, text: &str) -> Result<expr::Expr, String> {
        expr::Expr::parse(text, &|n| self.lookup_symbol(n), &*self.target)
    }

    /// Return addresses on the stack, innermost first ([`Target::call_stack`]).
    pub fn call_stack(&self) -> Vec<Frame> {
        self.target.call_stack()
    }

    /// Runs headless until the program ends, blocks for input with no keys queued, or `budget`
    /// instructions are executed.
    pub fn run_headless(&mut self, budget: u64) -> Event {
        self.target.run(budget)
    }
}

/// A saved session (see [`Session::save_state`]).
#[derive(Clone)]
pub struct SessionState {
    machine: rustemu_target::State,
    program: Option<Program>,
    mips_program: Option<rustemu_mips::asm::Program>,
    loaded: Option<(Loadable, Vec<u8>)>,
}

/// Default load segment used for COM/EXE programs (PSP).
pub const DEFAULT_PSP: u16 = PROGRAM_SEG;

/// A source-level step command.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum StepKind {
    /// Run the current source line (macro, CALL, INT) to completion.
    Over,
    /// Run until the current macro or procedure is left.
    Out,
}

/// State of a source-level step in progress.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct StepGoal {
    /// Over or Out.
    pub kind: StepKind,
    /// Macro code is stepped as its own lines (otherwise a macro invocation is one line).
    pub into_macros: bool,
    /// The line being stepped (None when there is no debug information).
    pub start: Option<View>,
    /// Call depth relative to the start: CALL/INT entering code +1, RET/RETF/IRET -1.
    pub depth: i32,
}

impl Session {
    /// Prepares a source-levelimpl Session {
    /// Prepares a source-level Step Over / Step Out from the current position.
    pub fn step_goal(&self, kind: StepKind, into_macros: bool) -> StepGoal {
        StepGoal { kind, into_macros, start: self.current_view(into_macros), depth: 0 }
    }

    /// Executes up to `budget` instructions towards `goal`.
    /// Returns `None` when the budget ran out, `Some(Event::Continue)` when the goal was reached,
    /// or the event that interrupted execution (input wait, termination, breakpoint, ...).
    pub fn run_step_goal(&mut self, goal: &mut StepGoal, budget: u64) -> Option<Event> {
        for _ in 0..budget {
            let pc = self.target.pc();
            let (flow, len) = self.target.flow_at(pc);
            let ev = self.target.step();
            if ev != Event::Continue {
                return Some(ev);
            }
            let new_pc = self.target.pc();
            match flow {
                // Entered a subroutine / user interrupt handler (BIOS services complete within the step).
                Flow::Call if new_pc != pc + len => goal.depth += 1,
                Flow::Return => goal.depth -= 1,
                _ => {}
            }
            if goal.depth < 0 {
                return Some(Event::Continue);
            }
            if self.target.breakpoints().contains(&new_pc) {
                return Some(Event::Breakpoint);
            }
            if goal.depth > 0 {
                continue;
            }
            let Some(start) = &goal.start else {
                // No debug info: Step Over is one instruction at this call depth.
                if goal.kind == StepKind::Over {
                    return Some(Event::Continue);
                }
                continue;
            };
            let Some(v) = self.view_at(new_pc, goal.into_macros) else {
                return Some(Event::Continue);
            };
            let done = match goal.kind {
                StepKind::Over => {
                    v.level < start.level || (v.level == start.level && (v.file, v.line) != (start.file, start.line))
                }
                StepKind::Out => v.level < start.level,
            };
            if done {
                return Some(Event::Continue);
            }
        }
        None
    }
}
