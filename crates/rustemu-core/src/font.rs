/// Returns the 8x8 glyph for a CP437 character. Characters without a bitmap use
/// block shapes where sensible and a hollow box otherwise.
pub fn glyph8x8(ch: u8) -> [u8; 8] {
    match ch {
        0x20..=0x7E => FONT[(ch - 0x20) as usize],
        0 | 0xFF => [0; 8],
        0xDB => [0xFF; 8],
        0xDC => [0, 0, 0, 0, 0xFF, 0xFF, 0xFF, 0xFF],
        0xDF => [0xFF, 0xFF, 0xFF, 0xFF, 0, 0, 0, 0],
        0xDD => [0xF0; 8],
        0xDE => [0x0F; 8],
        0xB0 => [0x22, 0x88, 0x22, 0x88, 0x22, 0x88, 0x22, 0x88],
        0xB1 => [0x55, 0xAA, 0x55, 0xAA, 0x55, 0xAA, 0x55, 0xAA],
        0xB2 => [0xDD, 0x77, 0xDD, 0x77, 0xDD, 0x77, 0xDD, 0x77],
        0xFE => [0, 0, 0x3C, 0x3C, 0x3C, 0x3C, 0, 0],
        _ => [0x00, 0x7E, 0x42, 0x42, 0x42, 0x42, 0x7E, 0x00],
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn cp437_roundtrip() {
        for b in 1..=255u8 {
            if b == 0xFF {
                continue;
            }
            assert_eq!(char_to_cp437(cp437_to_char(b)), b, "byte {b:02X}");
        }
        assert_eq!(cp437_to_char(0xC9), '╔');
    }
}
