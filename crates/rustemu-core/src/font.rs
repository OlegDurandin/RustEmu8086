/// Returns the 8x16 text-mode glyph of a CP437 character.
pub fn glyph8x16(ch: u8) -> [u8; 16] {
    FONT_8X16[ch as usize]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn cp437_roundtrip() {
        for b in 1..=255u8 {
            if b == 0xFF {
                continue;
            }
            assert_eq!(char_to_cp437(cp437_to_char(b)), b, "byte {b:02X}");
        }
        assert_eq!(cp437_to_char(0xC9), '╔');
    }

    #[test]
    fn every_visible_character_has_a_glyph() {
        for b in 0..=255u8 {
            let blank = glyph8x16(b).iter().all(|&row| row == 0);
            assert_eq!(blank, matches!(b, 0 | b' ' | 0xFF), "glyph {b:02X}");
        }
        assert_eq!(glyph8x16(0xDB), [0xFF; 16], "full block");
    }
}
