/// Converts a CP437 byte to the Unicode character it displays as.
pub fn cp437_to_char(b: u8) -> char {
    match b {
        0..=31 => CP437_LOW[b as usize],
        32..=126 => b as char,
        _ => CP437_HIGH[(b - 127) as usize],
    }
}

/// Converts a Unicode character to CP437 (unknown characters become `?`).
pub fn char_to_cp437(c: char) -> u8 {
    if (' '..='~').contains(&c) {
        return c as u8;
    }
    if let Some(i) = CP437_HIGH.iter().position(|&x| x == c) {
        return 127 + i as u8;
    }
    if let Some(i) = CP437_LOW.iter().position(|&x| x == c) {
        return i as u8;
    }
    b'?'
}

